def sphere_mesh(triangle_target):
    """A welded sphere mesh of roughly `triangle_target` triangles.

    manifold3d's sphere is generated by circular_segments; an icosphere-style
    refine(n) then multiplies triangle count by n^2 while staying a guaranteed
    valid 2-manifold. We pick segments + refine to hit the target, then return
    (verts float64, tris int64). r = 20.
    """
    import manifold3d as m
    # base sphere ~ a few hundred tris
    base = m.Manifold.sphere(20, circular_segments=32)
    base_tris = base.num_tri()
    if triangle_target <= base_tris:
        # coarsen via fewer segments
        for segs in (8, 12, 16, 24, 32):
            cand = m.Manifold.sphere(20, circular_segments=segs)
            if cand.num_tri() >= triangle_target:
                man = cand
                break
        else:
            man = base
    else:
        refine = max(1, int(round((triangle_target / base_tris) ** 0.5)))
        man = base.refine(refine) if refine > 1 else base
    return manifold_to_arrays(man)


def sphere_mesh_manifold(triangle_target):
    """Same as sphere_mesh but also returns the source Manifold (for volume ref)."""
    import manifold3d as m
    base = m.Manifold.sphere(20, circular_segments=32)
    base_tris = base.num_tri()
    if triangle_target <= base_tris:
        for segs in (8, 12, 16, 24, 32):
            cand = m.Manifold.sphere(20, circular_segments=segs)
            if cand.num_tri() >= triangle_target:
                man = cand
                break
        else:
            man = base
    else:
        refine = max(1, int(round((triangle_target / base_tris) ** 0.5)))
        man = base.refine(refine) if refine > 1 else base
    v, t = manifold_to_arrays(man)
    return v, t, man
